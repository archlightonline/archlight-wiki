/**
 * One-time extractor: pulls structured data (hero + stat chips + numbered
 * sections + tables/paragraphs/media) from the concept/design-lab source pages
 * into client/src/pages/wiki/wiki-data.ts, so the dedicated React page
 * components can render the original's layout faithfully without hand-transcribing.
 *
 * Run: node scripts/extract-wiki-data.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(__dirname, '..', 'archlight_wiki_v534_concepts_static_hosts_fixed');

const win = {};
// eslint-disable-next-line no-new-func
new Function('window', readFileSync(path.join(SRC, 'data/concept-routes.js'), 'utf8'))(win);
const routes = win.ARCHLIGHT_CONCEPT_ROUTES || [];

const ENT = {
  '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&apos;': "'", '&nbsp;': ' ',
  '&mdash;': '—', '&ndash;': '–', '&hellip;': '…', '&times;': '×', '&rsquo;': '’', '&lsquo;': '‘',
  '&rdquo;': '”', '&ldquo;': '“', '&deg;': '°', '&copy;': '©', '&middot;': '·',
};
const decode = (s) =>
  String(s || '')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&[a-z]+;/gi, (m) => ENT[m.toLowerCase()] ?? m);
const strip = (s) => decode(String(s || '').replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
const grab = (re, s) => strip((s.match(re) || [])[1] || '');

function parseTable(tableHtml) {
  const headers = [...tableHtml.matchAll(/<th\b[^>]*>([\s\S]*?)<\/th>/gi)].map((m) => strip(m[1]));
  const rows = [];
  for (const tr of tableHtml.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)) {
    const tds = [...tr[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)].map((m) =>
      decode(m[1].replace(/<br\s*\/?>/gi, ' / ').replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim(),
    );
    if (tds.length) rows.push(tds);
  }
  return { headers, rows };
}

function parseBody(bodyHtml) {
  const blocks = [];
  // Walk top-level elements of the body in document order.
  const re = /<p\b[^>]*>([\s\S]*?)<\/p>|<div class="[^"]*table-wrap[^"]*">([\s\S]*?)<\/table>\s*<\/div>\s*<\/div>|<table\b[^>]*>([\s\S]*?)<\/table>|<div class="[^"]*media-placeholder[^"]*">([\s\S]*?)<\/div>|<ul\b[^>]*>([\s\S]*?)<\/ul>/gi;
  let m;
  while ((m = re.exec(bodyHtml))) {
    if (m[1] !== undefined) {
      const t = strip(m[1]);
      if (t) blocks.push({ type: 'p', text: t });
    } else if (m[2] !== undefined || m[3] !== undefined) {
      const tbl = parseTable(m[0]);
      if (tbl.headers.length || tbl.rows.length) blocks.push({ type: 'table', ...tbl });
    } else if (m[4] !== undefined) {
      const cap = grab(/<b>([\s\S]*?)<\/b>/, m[4]);
      blocks.push({ type: 'media', caption: cap });
    } else if (m[5] !== undefined) {
      const items = [...m[5].matchAll(/<li\b[^>]*>([\s\S]*?)<\/li>/gi)].map((x) => strip(x[1])).filter(Boolean);
      if (items.length) blocks.push({ type: 'list', items });
    }
  }
  return blocks;
}

function parsePage(html, route) {
  const kicker = grab(/<div class="ut-kicker">([\s\S]*?)<\/div>/, html);
  const title = grab(/<h1 class="ut-title">([\s\S]*?)<\/h1>/, html) || route.title;
  const lead = grab(/<p class="ut-lead">([\s\S]*?)<\/p>/, html);
  const stats = [...html.matchAll(/<div class="ut-stat"><span>([\s\S]*?)<\/span><b>([\s\S]*?)<\/b><\/div>/g)].map((m) => ({
    label: strip(m[1]),
    value: strip(m[2]),
  }));
  const chip = grab(/<span class="ut-chip">([\s\S]*?)<\/span>/, html);

  const sections = [];
  const main = (html.match(/<main class="ut-main">([\s\S]*?)<\/main>/) || [])[1] || html;
  for (const sec of main.matchAll(/<section class="ut-panel ut-section"[^>]*>([\s\S]*?)<\/section>/g)) {
    const s = sec[1];
    const num = grab(/<div class="ut-num">([\s\S]*?)<\/div>/, s);
    const stitle = grab(/<h2>([\s\S]*?)<\/h2>/, s);
    const subtitle = grab(/<small>([\s\S]*?)<\/small>/, s);
    const body = (s.match(/<div class="ut-body">([\s\S]*?)<\/div>\s*$/) || s.match(/<div class="ut-body">([\s\S]*)/) || [])[1] || '';
    sections.push({ num, title: stitle, subtitle, blocks: parseBody(body) });
  }
  return { slug: route.id, title, kicker, lead, stats, chip, sections };
}

const out = {};
for (const r of routes) {
  let html;
  try {
    html = readFileSync(path.join(SRC, r.src), 'utf8');
  } catch {
    continue;
  }
  if (!/<h2/.test(html)) continue; // skip data-JS pages (classes/addons) with no inline sections
  out[r.id] = parsePage(html, r);
}

const header = `// AUTO-GENERATED by scripts/extract-wiki-data.mjs from the read-only concept
// source pages. Structured data for the dedicated wiki page components.
/* eslint-disable */

export type WikiBlock =
  | { type: 'p'; text: string }
  | { type: 'table'; headers: string[]; rows: string[][] }
  | { type: 'media'; caption: string }
  | { type: 'list'; items: string[] };

export interface WikiSection {
  num: string;
  title: string;
  subtitle: string;
  blocks: WikiBlock[];
}

export interface WikiPageData {
  slug: string;
  title: string;
  kicker: string;
  lead: string;
  stats: { label: string; value: string }[];
  chip: string;
  sections: WikiSection[];
}

export const WIKI_PAGE_DATA: Record<string, WikiPageData> = ${JSON.stringify(out, null, 2)};
`;

const dest = path.resolve(__dirname, '..', 'client', 'src', 'pages', 'wiki', 'wiki-data.ts');
writeFileSync(dest, header, 'utf8');
const counts = Object.entries(out).map(([k, v]) => `${k}(${v.sections.length}s)`).join(' ');
console.log(`Wrote ${dest}`);
console.log(`Pages: ${Object.keys(out).length}`);
console.log(counts);
